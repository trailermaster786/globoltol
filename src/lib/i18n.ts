export const useI18n = create<I18nState>((set, get) => ({
  lang: "en",
  setLang: (l) => set({ lang: l }),
  t: (key: string) => {
    const lang = get().lang;
    return translations[lang][key] ?? translations.en[key] ?? key;
  },
}));

export function isRTL() {
  return useI18n.getState().lang === "ar";
}
